// --- Slugs descriptivos para SEO ---------------------------------------------
// Convierte un texto en un slug apto para URL: sin acentos, en minúsculas y con
// guiones. Se recorta a ~60 caracteres para no generar URLs excesivamente largas.
export function slugify(text) {
  return String(text)
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    .replace(/-+$/g, "");
}

// Slug canónico de una propiedad: palabras clave del título + id al final.
// Ej: "casa-con-piscina-en-barrio-privado-exclusividad-y-confort-4"
export function getPropertySlug(property) {
  return `${slugify(property.title)}-${property.id}`;
}

// Resuelve una propiedad a partir de un slug. Acepta tanto el slug descriptivo
// (termina en "-<id>") como un id numérico puro (compatibilidad con URLs viejas).
export function findPropertyBySlug(slug) {
  const match = String(slug).match(/(\d+)$/);
  if (!match) return null;
  const id = parseInt(match[1], 10);
  return properties.find((p) => p.id === id) ?? null;
}
